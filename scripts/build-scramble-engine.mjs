/**
 * Builds the offline scramble engine: one HTML page that embeds cubing.js's
 * search worker, written to src/services/scramble-engine/engine-html.generated.ts.
 *
 * Why: cubing.js generates scrambles in a module Web Worker (and uses WebAssembly
 * for some events). Hermes, React Native's JS engine, has neither, so the app runs
 * this page inside a hidden WebView instead. Everything is inlined, so no network
 * is needed at runtime.
 *
 * Run after upgrading cubing:  npm run build:scramble-engine
 */
import { build } from 'esbuild';

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const cubingPkg = JSON.parse(readFileSync(join(root, 'node_modules/cubing/package.json'), 'utf8'));

// The worker entry has a stable file name inside the published package.
const workerEntry = join(root, 'node_modules/cubing/dist/lib/cubing/chunks/search-worker-entry.js');

const common = {
  bundle: true,
  write: false,
  minify: true,
  platform: 'browser',
  target: ['chrome100', 'safari15'],
  format: 'iife',
  legalComments: 'none',
  logLevel: 'warning',
};

const worker = await build({
  ...common,
  entryPoints: [workerEntry],
  // The entry exports its own URL for cubing's bundler workarounds; unused here.
  define: { 'import.meta.url': '""' },
});

const page = await build({
  ...common,
  entryPoints: [join(root, 'scripts/scramble-engine/page.ts')],
});

const escapeScript = (code) => code.replace(/<\/script/gi, '<\\/script');
const workerCode = escapeScript(worker.outputFiles[0].text);
const pageCode = escapeScript(page.outputFiles[0].text);

const html = `<!doctype html><html><head><meta charset="utf-8"><title>CUBIQ scramble engine</title></head><body>
<script type="text/js-worker" id="cubing-worker">${workerCode}</script>
<script>${pageCode}</script>
</body></html>`;

const out = `// GENERATED by scripts/build-scramble-engine.mjs from cubing@${cubingPkg.version}. Do not edit.
export const CUBING_VERSION = ${JSON.stringify(cubingPkg.version)};
export const SCRAMBLE_ENGINE_HTML = ${JSON.stringify(html)};
`;

const target = join(root, 'src/services/scramble-engine/engine-html.generated.ts');
writeFileSync(target, out);
console.log(`Wrote ${target} (${(out.length / 1024).toFixed(0)} KB, cubing@${cubingPkg.version})`);
